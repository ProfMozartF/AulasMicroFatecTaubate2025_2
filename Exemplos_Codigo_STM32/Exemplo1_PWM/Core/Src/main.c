#include "string.h"


/* Private variables ---------------------------------------------------------*/
ADC_HandleTypeDef hadc1;
TIM_HandleTypeDef htim1;
UART_HandleTypeDef huart1;
uint16_t ValorADCBruto = 0;
float SetPoint = 0.0;
char mensagem[50];
uint16_t PWM_Atual;

/* Private function prototypes -----------------------------------------------*/
void SystemClock_Config(void);
static void MX_GPIO_Init(void);
static void MX_ADC1_Init(void);
static void MX_TIM1_Init(void);
static void MX_USART1_UART_Init(void);


int main(void)
{
 /* MCU Configuration*/
  HAL_Init();
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ADC1_Init();
  MX_TIM1_Init();
  MX_USART1_UART_Init();
  HAL_ADC_Stop(&hadc1); //Desabilita o periférico
  HAL_ADCEx_Calibration_Start(&hadc1);
  __HAL_TIM_ENABLE(&htim1);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);


  while (1)
  {
	  HAL_ADC_Start( &hadc1); // Inicia a conversão ADC
	  HAL_ADC_PollForConversion(&hadc1, 10);  // Espera a conversão ser concluída
	  ValorADCBruto = HAL_ADC_GetValue(&hadc1);  // Lê o valor convertido - Devolve um numero entre 0 e 4096
	  HAL_ADC_Stop(&hadc1); //Desabilita o periférico

	  SetPoint = ValorADCBruto/40.95;
	  PWM_Atual = (uint16_t)SetPoint*10.0;
	  if(PWM_Atual<10){PWM_Atual=10;}
	  else if(PWM_Atual>990){PWM_Atual=990;}


	  TIM1->CCR1 = PWM_Atual; //Atualiza o valor do comparador que gera o Duty+

	  sprintf(mensagem, "VALOR ADC = %d\r\n",ValorADCBruto);
	  HAL_UART_Transmit(&huart1, (uint8_t*)mensagem, strlen(mensagem), 50);
	  sprintf(mensagem, "PWM Set = %.2f\r\n",SetPoint);
	  HAL_UART_Transmit(&huart1, (uint8_t*)mensagem, strlen(mensagem), 50);
	  sprintf(mensagem, "PWM Atual = %d\r\n",PWM_Atual);
	  HAL_UART_Transmit(&huart1, (uint8_t*)mensagem, strlen(mensagem), 50);

	  HAL_Delay(200);
  }

}//Fim do Main

